-- Auditoría por muestreo de decisiones de revisión ya aprobadas (A-10, riesgo R6: sesgo de automatización).
-- Una fila por decisión seleccionada; la semilla, la tasa y el valor sorteado quedan registrados para reproducirla.
CREATE TABLE review_audit (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapping_version_id BIGINT       NOT NULL,
    provider           VARCHAR(20)  NOT NULL,
    country            VARCHAR(2)   NOT NULL,
    version            INTEGER      NOT NULL,
    approved_by        VARCHAR(80)  NOT NULL,
    approved_at        TIMESTAMP WITH TIME ZONE,
    sample_id          VARCHAR(40)  NOT NULL,
    sample_rate        DOUBLE PRECISION NOT NULL,
    sample_seed        BIGINT       NOT NULL,
    draw               DOUBLE PRECISION NOT NULL,
    sampled_by         VARCHAR(80)  NOT NULL,
    sampled_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    second_reviewer    VARCHAR(80),
    outcome_note       VARCHAR(1000),
    decided_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_review_audit_version UNIQUE (mapping_version_id)
);
CREATE INDEX ix_review_audit_status ON review_audit (status, sampled_at);
