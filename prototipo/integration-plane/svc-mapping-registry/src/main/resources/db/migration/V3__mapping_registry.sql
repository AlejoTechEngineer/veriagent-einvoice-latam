-- Registro de versiones de mapeo (svc-mapping-registry). Compatible con H2 (modo PostgreSQL) y PostgreSQL.
CREATE TABLE mapping_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider      VARCHAR(20)  NOT NULL,
    country       VARCHAR(2)   NOT NULL,
    version       INTEGER      NOT NULL,
    profile       VARCHAR(40)  NOT NULL,
    body          TEXT         NOT NULL,
    sha256        VARCHAR(64)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    gate_passed   BOOLEAN      NOT NULL,
    verification  TEXT         NOT NULL,
    source        VARCHAR(20)  NOT NULL,
    proposal_ref  VARCHAR(80),
    created_by    VARCHAR(80)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    approved_by   VARCHAR(80),
    approved_at   TIMESTAMP WITH TIME ZONE,
    activated_by  VARCHAR(80),
    activated_at  TIMESTAMP WITH TIME ZONE,
    decision_note VARCHAR(1000),
    CONSTRAINT uq_mapping_version UNIQUE (provider, country, version)
);
CREATE INDEX ix_mapping_version_status ON mapping_version (provider, country, status);
