-- Núcleo del modelo de datos (apartado 4.4.5 del documento). Compatible con H2 (modo PostgreSQL) y PostgreSQL.

-- Estado y auditoría de cada comprobante. Una fila por comprobante; la clave de idempotencia es única.
CREATE TABLE authorization_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_key         VARCHAR(120) NOT NULL,
    correlation_id      VARCHAR(64)  NOT NULL,
    invoice_number      VARCHAR(30)  NOT NULL,
    document_type       VARCHAR(20)  NOT NULL,
    country             VARCHAR(2)   NOT NULL,
    channel             VARCHAR(10)  NOT NULL,
    provider            VARCHAR(20),
    mapping_version     INTEGER,
    status              VARCHAR(20)  NOT NULL,
    canonical_payload   TEXT         NOT NULL,
    transformed_payload TEXT,
    error_code          VARCHAR(60),
    error_message       VARCHAR(2000),
    authorization_number VARCHAR(80),
    retry_count         INTEGER      NOT NULL DEFAULT 0,
    last_actor          VARCHAR(80),
    received_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at             TIMESTAMP WITH TIME ZONE,
    authorized_at       TIMESTAMP WITH TIME ZONE,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_authorization_log_invoice_key UNIQUE (invoice_key),
    CONSTRAINT uq_authorization_log_correlation UNIQUE (correlation_id)
);
CREATE INDEX ix_authorization_log_status_received ON authorization_log (status, received_at);
CREATE INDEX ix_authorization_log_number ON authorization_log (invoice_number);

-- Línea de tiempo de estados de cada comprobante.
CREATE TABLE invoice_state_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_key   VARCHAR(120) NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    reason        VARCHAR(2000),
    actor         VARCHAR(80)  NOT NULL,
    correlation_id VARCHAR(64) NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_state_history_invoice ON invoice_state_history (invoice_key, occurred_at);

-- Registro de auditoría de solo anexado: quién hizo qué, con qué rol y sobre qué objeto.
CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(80)  NOT NULL,
    actor_role     VARCHAR(20)  NOT NULL,
    action         VARCHAR(60)  NOT NULL,
    target         VARCHAR(160) NOT NULL,
    details        VARCHAR(4000),
    correlation_id VARCHAR(64)  NOT NULL,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_log_target ON audit_log (target, occurred_at);

-- Trazabilidad de cada regla del kit hasta la norma (sección y huella digital del documento fuente).
CREATE TABLE rule_provenance (
    rule_id        VARCHAR(40)  NOT NULL,
    rule_version   VARCHAR(20)  NOT NULL,
    profile        VARCHAR(20)  NOT NULL,
    country        VARCHAR(2),
    provider       VARCHAR(20),
    section        VARCHAR(120) NOT NULL,
    source_document VARCHAR(160) NOT NULL,
    source_sha256  VARCHAR(64)  NOT NULL,
    effective_from DATE         NOT NULL,
    CONSTRAINT pk_rule_provenance PRIMARY KEY (rule_id, rule_version, profile, section)
);
