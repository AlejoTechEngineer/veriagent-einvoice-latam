-- Tablas de los servicios del plano de integración (Fase 2). Compatibles con H2 (modo PostgreSQL) y PostgreSQL.

-- Hallazgos del kit (JSON) del último intento de cada comprobante.
ALTER TABLE authorization_log ADD COLUMN findings TEXT;
ALTER TABLE authorization_log ADD COLUMN source_file VARCHAR(160);

-- Cuarentena: comprobantes (o entradas inválidas) que no pudieron completarse.
CREATE TABLE dlq_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_key   VARCHAR(120),
    source_ref    VARCHAR(200) NOT NULL,
    country       VARCHAR(2),
    provider      VARCHAR(20),
    stage         VARCHAR(20)  NOT NULL,
    category      VARCHAR(20)  NOT NULL,
    attempts      INTEGER      NOT NULL DEFAULT 0,
    last_error    VARCHAR(2000) NOT NULL,
    findings      TEXT,
    raw_payload   TEXT,
    status        VARCHAR(20)  NOT NULL,
    triage        TEXT,
    resolved_by   VARCHAR(80),
    resolution    VARCHAR(1000),
    correlation_id VARCHAR(64) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_dlq_status ON dlq_entry (status, created_at);
CREATE INDEX ix_dlq_invoice ON dlq_entry (invoice_key);

-- Archivos recibidos por la ingesta y su resumen.
CREATE TABLE ingest_file (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name   VARCHAR(160) NOT NULL,
    sha256      VARCHAR(64)  NOT NULL,
    received    INTEGER NOT NULL,
    accepted    INTEGER NOT NULL,
    duplicates  INTEGER NOT NULL,
    rejected    INTEGER NOT NULL,
    actor       VARCHAR(80) NOT NULL,
    correlation_id VARCHAR(64) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Lotes enviados a los proveedores.
CREATE TABLE provider_batch (
    batch_id    VARCHAR(80) PRIMARY KEY,
    provider    VARCHAR(20) NOT NULL,
    country     VARCHAR(2)  NOT NULL,
    size        INTEGER     NOT NULL,
    status      VARCHAR(20) NOT NULL,
    attempts    INTEGER     NOT NULL,
    last_error  VARCHAR(2000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at     TIMESTAMP WITH TIME ZONE,
    result_at   TIMESTAMP WITH TIME ZONE
);

CREATE TABLE provider_batch_item (
    batch_id    VARCHAR(80)  NOT NULL,
    invoice_key VARCHAR(120) NOT NULL,
    position    INTEGER      NOT NULL,
    CONSTRAINT pk_provider_batch_item PRIMARY KEY (batch_id, invoice_key)
);

-- Entregas de la respuesta al sistema de origen.
CREATE TABLE response_delivery (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_key VARCHAR(120) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    channel     VARCHAR(10)  NOT NULL,
    target      VARCHAR(200) NOT NULL,
    delivered_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_response_delivery_invoice ON response_delivery (invoice_key);

-- Archivo legal de solo anexado con cadena de huellas SHA-256 (ADR-07).
CREATE TABLE legal_archive_entry (
    seq            BIGINT       PRIMARY KEY,
    invoice_key    VARCHAR(120) NOT NULL,
    country        VARCHAR(2)   NOT NULL,
    object_path    VARCHAR(300) NOT NULL,
    object_sha256  VARCHAR(64)  NOT NULL,
    prev_hash      VARCHAR(64)  NOT NULL,
    entry_hash     VARCHAR(64)  NOT NULL,
    retention_until DATE        NOT NULL,
    archived_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_legal_archive_invoice UNIQUE (invoice_key)
);

-- Pendientes del archivo legal (mejor esfuerzo, con reintento asíncrono).
CREATE TABLE archive_pending (
    invoice_key  VARCHAR(120) PRIMARY KEY,
    attempts     INTEGER      NOT NULL,
    last_error   VARCHAR(2000),
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL
);
